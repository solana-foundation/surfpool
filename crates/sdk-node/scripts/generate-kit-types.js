/**
 * Regenerates the TypeScript bindings for the surfnet_* cheatcode wire types
 * from the Rust source of truth (crates/types, `ts-bindings` feature).
 *
 * Output goes to surfpool-sdk/kit/generated/ and is committed; CI regenerates
 * and fails on any diff, so the bindings can never drift from the Rust types.
 */
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..", "..", "..");
const generatedDir = path.resolve(
  __dirname,
  "..",
  "surfpool-sdk",
  "kit",
  "generated",
);

const HEADER = `// @generated by ts-rs from the Rust types in crates/types.\n// Do not edit; run \`npm run generate:kit-types\` in crates/sdk-node instead.\n`;

fs.rmSync(generatedDir, { recursive: true, force: true });

// No test-name filter: this must run the whole surfpool-types suite so the
// mirror serialization-equivalence and wire-key guard tests in ts_bindings.rs
// gate every regeneration, not just emit files.
execFileSync("cargo", ["test", "-p", "surfpool-types", "--features", "ts-bindings"], {
  cwd: repoRoot,
  env: {
    ...process.env,
    TS_RS_EXPORT_DIR: generatedDir,
    // The package compiles this directory to both CJS and ESM; Node ESM
    // requires explicit extensions on relative imports.
    TS_RS_IMPORT_EXTENSION: "js",
  },
  stdio: "inherit",
});

const files = fs
  .readdirSync(generatedDir)
  .filter((name) => name.endsWith(".ts"))
  .sort();

for (const name of files) {
  const filePath = path.join(generatedDir, name);
  const content = fs.readFileSync(filePath, "utf8");
  fs.writeFileSync(filePath, HEADER + content);
}

const barrel = files
  .map((name) => {
    const module = `./${name.replace(/\.ts$/, "")}.js`;
    // methods.ts exports a runtime const; everything else is type-only.
    return name === "methods.ts"
      ? `export * from "${module}";`
      : `export type * from "${module}";`;
  })
  .join("\n");
fs.writeFileSync(path.join(generatedDir, "index.ts"), `${HEADER}${barrel}\n`);

console.log(`Generated ${files.length} binding files in ${generatedDir}`);
